/*
 * golden.c — the oracle.
 *
 * Runs every checked kernel natively and prints golden/golden.h. Compiled from
 * the same kernel sources the guest runs, so the two differ only in the
 * machine underneath — which is the whole point.
 *
 * Built with -O1 -fno-tree-vectorize -ffp-contract=off. Not superstition:
 * reassociating a floating-point reduction or fusing a multiply-add changes
 * results in the last ulp, and the checksums fold in raw bit patterns. GCC
 * will not reassociate FP without -ffast-math, but x86-64 will happily
 * contract into an FMA if it is allowed to, and MIPS III has no FMA to match
 * it with.
 */

#include "benchlib.h"

extern const struct bench_group *const all_bgroups[];
extern const unsigned n_bgroups;

void bench_init(void);

int main(void)
{
    unsigned gi, bi, total = 0;

    bench_init();

    printf("/* golden.h — generated by bench/gen/golden.c; do not edit.\n");
    printf(" *\n");
    printf(" * Expected checksums, computed natively. Regenerate with:\n");
    printf(" *     make -C bench golden\n");
    printf(" */\n");
    printf("#ifndef GOLDEN_H\n#define GOLDEN_H\n\n");

    for (gi = 0; gi < n_bgroups; gi++) total += all_bgroups[gi]->count;
    printf("#define BENCH_MAX_RESULTS %u\n\n", total + 16);

    printf("struct golden_entry { const char *name; u64 sum; };\n");
    printf("static const struct golden_entry goldens[] = {\n");

    for (gi = 0; gi < n_bgroups; gi++) {
        const struct bench_group *g = all_bgroups[gi];
        for (bi = 0; bi < g->count; bi++) {
            const struct bench *b = &g->benches[bi];
            u64 sum;
            if (!b->verify) continue;
            work_reset();
            sum = b->verify();
            printf("    { \"%s\", 0x%016llxull },\n", b->name, (unsigned long long)sum);
            fprintf(stderr, "  %-24s %016llx\n", b->name, (unsigned long long)sum);
        }
    }

    printf("};\n");
    printf("static const unsigned n_goldens = sizeof(goldens) / sizeof(goldens[0]);\n\n");
    printf("#endif /* GOLDEN_H */\n");
    return 0;
}
