#!/usr/bin/env python3
"""Generate src/avail.rs: which OpenGL version or extensions provide each entry
point the service can look up.

  python3 iris-hostgl/tools/gl_avail.py

A backend whose library answers every name (glvnd and Mesa both hand out a
do-nothing stub for any `gl*` name asked for) cannot say an entry point is
missing by returning null, and the service relies on that: a missing
`glFooSGI` falls back to `glFoo`. Such a backend asks this table instead,
against the version and extensions of the context it made.

The names are those in calls.rs's NAMES, plus each with its vendor suffix
taken off the way `Exec::func` does. Requirements come from the pinned
registry (khronos/gl.xml): the `gl` API's versions (compatibility profile, so
nothing is ever removed) and the extensions that support `gl`.
"""
import os
import re
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src")
SUFFIXES = ("ARB", "EXT", "SGIX", "SGIS", "SGI")


def names():
    text = open(os.path.join(SRC, "calls.rs")).read()
    i = text.index("pub const NAMES")
    body = text[i : text.index("];", i)]
    out = set()
    for n in re.findall(r'"(\w+)"', body):
        out.add(n)
        core = n
        for s in SUFFIXES:  # Exec::func strips these in this order
            core = core[: -len(s)] if core.endswith(s) else core
        out.add(core)
    return out


def requirements():
    root = ET.parse(os.path.join(HERE, "khronos", "gl.xml")).getroot()
    req = {}
    for f in root.findall("feature"):
        if f.get("api") != "gl":
            continue
        for r in f.findall("require"):
            if r.get("profile") == "core":
                continue
            for c in r.findall("command"):
                req.setdefault(c.get("name"), set()).add(f.get("number"))
    for e in root.find("extensions"):
        if "gl" not in e.get("supported", "").split("|"):
            continue
        for r in e.findall("require"):
            if r.get("api") not in (None, "gl"):
                continue
            for c in r.findall("command"):
                req.setdefault(c.get("name"), set()).add(e.get("name"))
    return req


def main():
    req = requirements()
    rows = []
    for n in sorted(names()):
        if n in req:
            # Versions first, lowest first; then extensions by name.
            r = sorted(req[n], key=lambda x: (not x[0].isdigit(), [int(p) for p in x.split(".")] if x[0].isdigit() else x))
            rows.append(f'    ("{n}", &[{", ".join(chr(34) + x + chr(34) for x in r)}]),')
    out = [
        "// Generated by tools/gl_avail.py from tools/khronos/gl.xml -- do not edit.",
        "//",
        "// Each entry point the service may look up, with what provides it: a GL",
        '// version ("1.2") or an extension. Sorted by name. A name not here is',
        "// provided by nothing a host could have.",
        "",
        "pub const AVAIL: &[(&str, &[&str])] = &[",
        *rows,
        "];",
        "",
    ]
    open(os.path.join(SRC, "avail.rs"), "w").write("\n".join(out))
    print(f"avail.rs: {len(rows)} entry points ({len(names()) - len(rows)} names the registry has not got)")


main()
