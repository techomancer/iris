#!/usr/bin/env python3
"""Generate src/vga_font.rs from SGI's Screen 16 bitmap font.

Reads the X11 PCF file (plain or gzipped) and writes one 16-byte bitmap per
code 0-255, MSB = leftmost pixel. Codes the font has no glyph for are blank.

    tools/gen-screen-font.py [--font Scr16.pcf.gz] [--out src/vga_font.rs]
                             [--preview sheet.png]

The font ships as sgi-fonts (SuSE RPM, Gentoo media-fonts/sgi-fonts).
"""

import argparse
import gzip
import os
import struct
import sys
import zlib

PCF_METRICS = 1 << 2
PCF_BITMAPS = 1 << 3
PCF_BDF_ENCODINGS = 1 << 5

FORMAT_COMPRESSED_METRICS = 0x100
FORMAT_BYTE_MSB = 1 << 2  # multi-byte integers are big endian
FORMAT_BIT_MSB = 1 << 3  # leftmost pixel is the top bit of a byte

CELL_W = 8
CELL_H = 16
NO_GLYPH = 0xFFFF
SCALE = 2  # preview pixels per font pixel


def read_tables(data):
    if data[:4] != b"\x01fcp":
        sys.exit("not a PCF file")
    count = struct.unpack_from("<I", data, 4)[0]
    tables = {}
    for i in range(count):
        kind, fmt, size, offset = struct.unpack_from("<4I", data, 8 + i * 16)
        tables[kind] = (fmt, offset)
    return tables


def read_metrics(data, table):
    """Return (left bearing, right bearing, ascent, descent) per glyph."""
    fmt, off = table
    if fmt & FORMAT_COMPRESSED_METRICS:
        endian = ">" if fmt & FORMAT_BYTE_MSB else "<"
        count = struct.unpack_from(endian + "H", data, off + 4)[0]
        raw = [data[off + 6 + i * 5 : off + 11 + i * 5] for i in range(count)]
        return [(r[0] - 0x80, r[1] - 0x80, r[3] - 0x80, r[4] - 0x80) for r in raw]
    endian = ">" if fmt & FORMAT_BYTE_MSB else "<"
    count = struct.unpack_from(endian + "I", data, off + 4)[0]
    out = []
    for i in range(count):
        lsb, rsb, _width, asc, desc, _attr = struct.unpack_from(
            endian + "5hH", data, off + 8 + i * 12
        )
        out.append((lsb, rsb, asc, desc))
    return out


def read_bitmaps(data, table):
    """Return (bitmap bytes, per-glyph offsets, row padding, bit order is MSB)."""
    fmt, off = table
    endian = ">" if fmt & FORMAT_BYTE_MSB else "<"
    count = struct.unpack_from(endian + "I", data, off + 4)[0]
    offsets = struct.unpack_from(f"{endian}{count}I", data, off + 8)
    sizes = struct.unpack_from(endian + "4I", data, off + 8 + count * 4)
    pad = 1 << (fmt & 3)
    start = off + 8 + count * 4 + 16
    return data[start : start + sizes[fmt & 3]], offsets, pad, bool(fmt & FORMAT_BIT_MSB)


def read_encodings(data, table):
    """Return a code -> glyph index map, for single-byte codes only."""
    fmt, off = table
    endian = ">" if fmt & FORMAT_BYTE_MSB else "<"
    min_col, max_col, min_row, max_row, _default = struct.unpack_from(
        endian + "5H", data, off + 4
    )
    if min_row != 0 or max_row != 0:
        sys.exit("expected a single-byte encoding")
    encoding = {}
    for col in range(min_col, max_col + 1):
        glyph = struct.unpack_from(endian + "H", data, off + 14 + (col - min_col) * 2)[0]
        if glyph != NO_GLYPH and col < 256:
            encoding[col] = glyph
    return encoding


def load_font(path):
    with open(path, "rb") as f:
        data = f.read()
    if data[:2] == b"\x1f\x8b":
        data = gzip.decompress(data)
    tables = read_tables(data)
    metrics = read_metrics(data, tables[PCF_METRICS])
    bits, offsets, pad, bit_msb = read_bitmaps(data, tables[PCF_BITMAPS])
    encoding = read_encodings(data, tables[PCF_BDF_ENCODINGS])

    ascent = max(metrics[g][2] for g in encoding.values())
    descent = max(metrics[g][3] for g in encoding.values())
    if ascent + descent != CELL_H:
        sys.exit(f"font is {ascent + descent} pixels tall, want {CELL_H}")

    table = bytearray(256 * CELL_H)
    for code, glyph in encoding.items():
        lsb, rsb, asc, desc = metrics[glyph]
        if lsb < 0 or rsb > CELL_W:
            sys.exit(f"glyph {code:#x} leaves the {CELL_W}-pixel cell ({lsb}..{rsb})")
        stride = ((rsb - lsb + 7) // 8 + pad - 1) // pad * pad
        for row in range(asc + desc):
            byte = bits[offsets[glyph] + row * stride]
            if not bit_msb:
                byte = int(f"{byte:08b}"[::-1], 2)
            # The bitmap starts at the left bearing, the cell at the origin.
            table[code * CELL_H + ascent - asc + row] = byte >> lsb
    return bytes(table), sorted(encoding)


def rust_source(table, font_name):
    lines = [
        f"// Generated by tools/gen-screen-font.py from {font_name}. Do not edit.",
        "//",
        "// SGI Screen 16 (-sgi-screen-medium-r-normal--16-160-72-72-m-80-iso8859-1),",
        "// Copyright Silicon Graphics, Inc., distributed under the MIT license.",
        "// 256 ISO 8859-1 codes x 16 rows, MSB = leftmost pixel; codes the font has",
        "// no glyph for are blank.",
        "",
        f"pub static SCREEN_8X16: [u8; {len(table)}] = [",
    ]
    for i in range(0, len(table), CELL_H):
        lines.append("    " + " ".join(f"0x{b:02X}," for b in table[i : i + CELL_H]))
    lines += ["];", ""]
    return "\n".join(lines)


def write_png(path, width, height, gray):
    def chunk(kind, body):
        crc = zlib.crc32(kind + body)
        return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", crc)

    rows = b"".join(
        b"\0" + bytes(gray[y * width : (y + 1) * width]) for y in range(height)
    )
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(chunk(b"IHDR", struct.pack(">2I5B", width, height, 8, 0, 0, 0, 0)))
        f.write(chunk(b"IDAT", zlib.compress(rows)))
        f.write(chunk(b"IEND", b""))


def write_preview(path, table):
    """Write a 16x16 sheet of every code, with a one-pixel gap between cells."""
    pitch_x = (CELL_W + 1) * SCALE
    pitch_y = (CELL_H + 1) * SCALE
    width = pitch_x * 16
    height = pitch_y * 16
    gray = bytearray(b"\x20" * (width * height))
    for code in range(256):
        for row in range(CELL_H * SCALE):
            byte = table[code * CELL_H + row // SCALE]
            for col in range(CELL_W * SCALE):
                if byte >> (7 - col // SCALE) & 1:
                    x = (code % 16) * pitch_x + col
                    y = (code // 16) * pitch_y + row
                    gray[y * width + x] = 0xFF
    write_png(path, width, height, gray)


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--font", default="/usr/share/fonts/sgi-fonts/Scr16.pcf.gz")
    parser.add_argument("--out", default=os.path.join(root, "src", "vga_font.rs"))
    parser.add_argument("--preview", help="also write a PNG sheet of every glyph")
    args = parser.parse_args()

    table, codes = load_font(args.font)
    with open(args.out, "w") as f:
        f.write(rust_source(table, os.path.basename(args.font)))
    if args.preview:
        write_preview(args.preview, table)
    print(f"{args.out}: {len(codes)} glyphs, codes {codes[0]:#x}..{codes[-1]:#x}")


if __name__ == "__main__":
    main()
