#!/bin/bash
# Boot an installed IRIX disk in iris (Indy, R4400) twice, and pass if both
# boots reach the login:
#   1. serial console (console=d): "login:" reaches serial.
#   2. graphics console (console=g): IRIX draws its login on the framebuffer
#      only, so `iris-ci screen-wait` waits for the screen to match $GOLDEN.
#      On a mismatch it leaves gfx-screen.png and gfx-diff.png in <out-dir>.
# Each check is also a case in <out-dir>/boot-test.xml, a JUnit report for CI.
# The serial boot stays alongside the graphics one: it is cheap, and when a
# boot fails its transcript shows how far it got, which a screenshot does not.
# Usage: ci-boot-test.sh <bin-dir> <disk-image> <out-dir> [timeout-seconds]
# The timeout applies to each boot.

set -u

BIN_DIR=$1
IMAGE=$2
OUT=$3
TIMEOUT=${4:-900}
# A screenshot of the login screen of the disk CI boots.
GOLDEN=${GOLDEN:-$(cd "$(dirname "$0")" && pwd)/boot-goldens/indy-irix53.png}

EXE=""
case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) EXE=".exe" ;; esac
IRIS="$(cd "$BIN_DIR" && pwd)/iris$EXE"
IRIS_CI="$(cd "$BIN_DIR" && pwd)/iris-ci$EXE"
IMAGE="$(cd "$(dirname "$IMAGE")" && pwd)/$(basename "$IMAGE")"

mkdir -p "$OUT"
cd "$OUT" || exit 1

# CI socket: TCP on Windows; a short /tmp Unix socket elsewhere (macOS caps paths at 104 bytes).
if [ -n "$EXE" ]; then
  export IRIS_SOCKET="127.0.0.1:19851"
else
  export IRIS_SOCKET="/tmp/iris-boot-$$.sock"
fi

# Forward slashes in TOML work on every host, Windows included.
IMAGE_TOML=$IMAGE
if [ -n "$EXE" ] && command -v cygpath >/dev/null; then
  IMAGE_TOML=$(cygpath -m "$IMAGE")
fi

cat > boot-test.toml <<EOF
# Generated by scripts/ci-boot-test.sh.
no_audio   = true
nvram      = "nvram.bin"
serial_log = "serial.log"
ci         = true
ci_socket  = "$IRIS_SOCKET"

[scsi.1]
path    = "$IMAGE_TOML"
cdrom   = false
overlay = true
EOF

rm -f nvram.bin serial.log phase-a.log transcript.log iris-*.log gfx-*.png boot-test.xml

log() { echo "[boot-test $(date -u +%H:%M:%S)] $*"; }
ic() { "$IRIS_CI" "$@"; }

# The JUnit cases, written to boot-test.xml on exit by `iris-ci junit`.
# check <pass|fail> <seconds> <name> [text]
CASES=()
check() { CASES+=(--case "$1|$2|$3${4:+|$4}"); }
# fail <message>: fail the check now under way and stop.
CHECK="start iris"
fail() { log "$1"; check fail 0 "$CHECK" "$1"; exit 1; }

# stop_iris: ask iris to quit and kill it if it has not within 5 s. QUIT says
# how it ended: "exit N" when it quit by itself, "killed" otherwise.
IRIS_PID=""
QUIT=""
stop_iris() {
  [ -z "$IRIS_PID" ] && return
  ic quit >/dev/null 2>&1 || true
  QUIT=killed
  for _ in 1 2 3 4 5; do kill -0 "$IRIS_PID" 2>/dev/null || { QUIT=exited; break; }; sleep 1; done
  kill "$IRIS_PID" 2>/dev/null || true
  [ -n "$EXE" ] && { taskkill //F //IM "iris$EXE" >/dev/null 2>&1 || true; }
  wait "$IRIS_PID" 2>/dev/null
  local rc=$?
  [ "$QUIT" = exited ] && QUIT="exit $rc"
  IRIS_PID=""
  [ -z "$EXE" ] && rm -f "$IRIS_SOCKET"
}

# check_quit <name>: stop iris and check that it quit by itself, status 0. A
# machine that will not stop when asked would hang a user's session too.
check_quit() {
  [ -z "$IRIS_PID" ] && return
  stop_iris
  if [ "$QUIT" = "exit 0" ]; then
    check pass 0 "$1"
  else
    check fail 0 "$1" "iris after quit: $QUIT"; RESULT=1
  fi
}

finish() {
  stop_iris
  # ${CASES[@]+...}: bash 3.2, on macOS, calls an empty array unbound.
  ic junit boot-test.xml --suite "boot.$(uname -s)" ${CASES[@]+"${CASES[@]}"} \
    || log "could not write boot-test.xml"
}
trap finish EXIT

# start_iris <log> [extra iris args...]: launch and wait for the CI socket.
start_iris() {
  local logf=$1; shift
  "$IRIS" --config boot-test.toml "$@" > "$logf" 2>&1 &
  IRIS_PID=$!
  for _ in $(seq 1 60); do
    ic -q ping >/dev/null 2>&1 && return 0
    if ! kill -0 "$IRIS_PID" 2>/dev/null; then
      cat "$logf"; fail "iris exited before the CI socket came up"
    fi
    sleep 1
  done
  cat "$logf"; fail "CI socket never came up"
}

# monitor_cmd <command>: type a PROM Command Monitor line, wait for the prompt.
monitor_cmd() {
  ic -q serial-send "$1" || return 1
  ic serial-wait --timeout 30 ">> " >> phase-a.log 2>&1
}

# ── Phase A: seed NVRAM ──────────────────────────────────────────────────────
# A blank NVRAM has no boot path; headless puts the PROM on serial so we can
# setenv. The console variable then decides where IRIX puts its login.

# seed_nvram <console>
seed_nvram() {
  log "phase A: seeding NVRAM (headless, console=$1)"
  CHECK="seed NVRAM (console=$1)"
  local start=$(date +%s)
  # A seeded NVRAM has AutoLoad on, and the PROM would boot past its menu.
  rm -f nvram.bin
  start_iris "iris-phase-a-$1.log" --headless
  ic -q start
  if ! ic serial-wait --timeout 180 "Option?" >> phase-a.log 2>&1; then
    cat phase-a.log; fail "phase A: PROM menu never appeared on serial"
  fi
  ic -q serial-send 5   # Enter Command Monitor
  ic serial-wait --timeout 30 ">> " >> phase-a.log 2>&1 \
    || { cat phase-a.log; fail "phase A: no Command Monitor prompt"; }
  for c in \
    "setenv -f SystemPartition scsi(0)disk(1)rdisk(0)partition(8)" \
    "setenv -f OSLoadPartition scsi(0)disk(1)rdisk(0)partition(0)" \
    "setenv -f OSLoadFilename /unix" \
    "setenv -f AutoLoad Yes" \
    "setenv -f console $1" \
    "printenv"; do
    monitor_cmd "$c" || { cat phase-a.log; fail "phase A: '$c' got no prompt back"; }
  done
  ic -q rtc-save || fail "phase A: rtc-save failed"
  stop_iris
  check pass $(( $(date +%s) - start )) "$CHECK"
  log "phase A: done"
}

# ── Phase B: boot on the serial console ──────────────────────────────────────
# console=d + AutoLoad: the PROM boots the disk unattended and the login
# arrives on serial, where the wait below sees it.

seed_nvram d
CHECK="serial console: login prompt"
start_iris iris.log
log "phase B: booting; deadline ${TIMEOUT}s"
ic -q start

START=$(date +%s)
RESULT=1

while :; do
  NOW=$(date +%s)
  ELAPSED=$((NOW - START))

  ic serial-read >> transcript.log 2>/dev/null || true

  if ! kill -0 "$IRIS_PID" 2>/dev/null; then
    log "iris exited after ${ELAPSED}s"; IRIS_PID=""
    check fail "$ELAPSED" "$CHECK" "iris exited after ${ELAPSED}s"; break
  fi

  if grep -q 'login:' transcript.log; then
    log "login prompt after ${ELAPSED}s"
    check pass "$ELAPSED" "$CHECK"
    RESULT=0
    break
  fi

  if [ "$ELAPSED" -ge "$TIMEOUT" ]; then
    log "no login prompt within ${TIMEOUT}s"
    check fail "$ELAPSED" "$CHECK" "no login prompt within ${TIMEOUT}s"; break
  fi
  sleep 5
done

check_quit "iris quits when asked, serial boot"
log "last serial output:"
tail -n 40 transcript.log

# ── Phase C: boot on the graphics console ────────────────────────────────────
# console=g: the login is drawn on the framebuffer and serial stays silent.

seed_nvram g
CHECK="graphics console: login screen"
start_iris iris-gfx.log
log "phase C: booting; deadline ${TIMEOUT}s"
ic -q start
START=$(date +%s)
# The last line screen-wait prints gives the pixel count, matched or not.
if SAID=$(ic screen-wait "$GOLDEN" --timeout "$TIMEOUT" \
            --actual gfx-screen.png --diff gfx-diff.png 2>&1); then
  echo "$SAID"
  log "graphics login matches $(basename "$GOLDEN")"
  check pass $(( $(date +%s) - START )) "$CHECK" "$(echo "$SAID" | tail -n 1)"
else
  echo "$SAID"
  log "graphics login does not match $(basename "$GOLDEN")"
  check fail $(( $(date +%s) - START )) "$CHECK" "$(echo "$SAID" | tail -n 1)"
  RESULT=1
fi
check_quit "iris quits when asked, graphics boot"
exit $RESULT
