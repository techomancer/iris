/// Decode the bundled window/taskbar icon (256×256 RGBA PNG, generated by
/// `scripts/generate-icon.sh` from `iris-gui/assets/icon-original.png`).
/// Decoded with the `png` crate that iris-gui already depends on, so no extra
/// image dependency is pulled in.
fn load_icon() -> egui::IconData {
    const ICON_PNG: &[u8] = include_bytes!("../assets/icons/icon-256.png");
    let decoder = png::Decoder::new(std::io::Cursor::new(ICON_PNG));
    let mut reader = decoder.read_info().expect("decode icon PNG header");
    let mut rgba = vec![0u8; reader.output_buffer_size().expect("icon PNG size fits usize")];
    let info = reader.next_frame(&mut rgba).expect("decode icon PNG pixels");
    rgba.truncate(info.buffer_size());
    egui::IconData {
        rgba,
        width: info.width,
        height: info.height,
    }
}

/// Developer tools retain the source launch directory when machine selection
/// changes the process cwd. Child processes receive an explicit directory.
fn launch_dir() -> &'static std::path::Path {
    static DIR: std::sync::OnceLock<PathBuf> = std::sync::OnceLock::new();
    DIR.get_or_init(|| std::env::current_dir().unwrap_or_else(|_| PathBuf::from(".")))
}

fn developer_binary(name: &str) -> PathBuf {
    let suffix = if cfg!(windows) { ".exe" } else { "" };
    launch_dir().join(format!("target/release/{name}{suffix}"))
}


/// Resolve a config path to an absolute string for display — a relative path is
/// joined to the process working directory (where the emulator actually looks
/// for it), so the user never sees a bare `scsi3.raw` with no idea where it is.
fn abs_path(p: &str) -> String {
    let path = std::path::Path::new(p);
    if path.is_absolute() || p.is_empty() {
        return p.to_string();
    }
    std::env::current_dir()
        .map(|d| d.join(path).to_string_lossy().into_owned())
        .unwrap_or_else(|_| p.to_string())
}

/// Picker results use the same path spelling as the saved config, including
/// live CD-ROM commands and snapshot provenance.
fn picked_path(path: &std::path::Path) -> String {
    let relative = std::env::current_dir().ok().and_then(|dir| machines::relative(&dir, path));
    relative.unwrap_or_else(|| path.to_path_buf()).to_string_lossy().into_owned()
}


/// Repaint follow-up (ms) while frames are arriving. The frame sinks wake the
/// GUI the instant a frame is published, so this is only insurance against a
/// lost wake: it has to be short enough to keep a 60 Hz stream smooth, and it
/// is never reached when the wake does its job.
const REPAINT_FRAME_MS: u64 = 8;

/// Repaint fallback (ms) when no frame was taken on the previous pass — a
/// settled screen, a stopped machine, or the config editor being open. egui
/// still needs to run often enough that the status footer, toasts, menus and
/// text entry feel live; 4 Hz is plenty for all of those, and it is what the
/// GUI used to spend on a static desktop 60 times a second.
const REPAINT_IDLE_MS: u64 = 250;

/// Size (egui points) to draw a framebuffer of `px` native pixels in `avail`
/// points at `ppp` device pixels per point, and whether that size is a whole
/// number of device pixels per emulated pixel (so NEAREST is pixel-exact).
///
/// `max_scale` (points per emulated pixel) is the View > VM screen setting and
/// caps the picture: a window with room for more (fullscreen, maximised, a
/// manual resize) centres the display at the chosen scale instead of blowing
/// it up to a fractional, filtered one. Only a window too small for it shrinks
/// the picture to fit.
///
/// Only ever snaps *down* to the integer scale, never up: overhanging the
/// panel would clip rows off the picture, which is the bug this exists to fix.
/// Off an integer, returns the aspect-preserving fit to be drawn with LINEAR.
fn fb_draw_size(avail: egui::Vec2, px: egui::Vec2, ppp: f32, max_scale: f32) -> (egui::Vec2, bool) {
    let ((w, h), integer) = iris_gui_core::controller::display::draw_size((avail.x, avail.y), (px.x, px.y), ppp, max_scale, false);
    (egui::vec2(w, h), integer)
}

/// Centre the framebuffer in `outer` and put its edges on the device-pixel
/// grid. `centered_and_justified` leaves the origin on a fractional device
/// pixel whenever the leftover space is odd, and NEAREST then samples across
/// texel boundaries and drops or doubles rows even at an exact integer scale.
fn fb_draw_rect(outer: egui::Rect, px: egui::Vec2, ppp: f32, max_scale: f32) -> (egui::Rect, bool) {
    let (size, nearest) = fb_draw_size(outer.size(), px, ppp, max_scale);
    let rect = egui::Rect::from_center_size(outer.center(), size);
    if ppp <= 0.0 { return (rect, nearest); }
    let snap = |v: f32| (v * ppp).round() / ppp;
    let min = egui::pos2(snap(rect.min.x), snap(rect.min.y));
    (egui::Rect::from_min_size(min, egui::vec2(snap(size.x), snap(size.y))), nearest)
}

/// Set when a signal asked the window to close: see `main`.
static CLOSE_ON_SIGNAL: std::sync::atomic::AtomicBool = std::sync::atomic::AtomicBool::new(false);

fn main() -> eframe::Result<()> {
    // env_logger, plus the tap that tells a file dialog that never appeared
    // from one the user cancelled (see `filedialog`).
    filedialog::init_logging();
    // Prevent the iris lib from calling process::exit on guest soft-power-off
    // or CI `quit`. iris-gui never wants the embedder to die from a guest event.
    // Set this once, before any worker thread can read it.
    std::env::set_var("IRIS_NO_EXIT_ON_POWEROFF", "1");
    // Terminate a still-alive previous instance (a crash/hang or forgotten
    // copy that would otherwise keep the monitor/serial ports bound) and claim
    // the single-instance lock for ourselves.
    single_instance::acquire();
    launch_dir(); // Capture the source launch directory before selecting a machine.
    let prefs = GuiSettings::load();
    i18n::set_language(&prefs.language);
    // Force the interpreter on the Mac App Store build. Cranelift (MIPS JIT and
    // the always-on REX3 draw-shader and IMPACT raster JITs) allocates executable memory with
    // mmap+mprotect, not MAP_JIT. The App Sandbox only permits MAP_JIT pages
    // (com.apple.security.cs.allow-jit is the sole code-signing entitlement MAS
    // allows; allow-unsigned-executable-memory / disable-executable-page-
    // protection are rejected by App Review), so the first JITed REX3 draw is
    // killed with SIGKILL/CODESIGNING "Invalid Page" on the REX3-Processor
    // thread — right after the emulator window opens, before any video. Set
    // once, before any worker thread (CPU / REX3) can read it.
    let viewport = egui::ViewportBuilder::default()
        .with_title(t!("app-name"))
        // app_id sets the X11 WM_CLASS / Wayland app_id so the compositor can
        // match an installed .desktop/icon (icons regenerated by
        // scripts/generate-icon.sh from iris-gui/assets/icon-original.png).
        .with_app_id("iris-gui")
        .with_icon(load_icon())
        // Open large enough for the 1280×1024 display + chrome so it looks right
        // immediately; clamp to the monitor so it can't overflow a smaller
        // screen. Persisted size (once saved) takes precedence over the default.
        .with_inner_size(WINDOW_DEFAULT_SIZE)
        .with_clamp_size_to_monitor_size(true)
        // Start hidden so the first frame can fit the window to the monitor
        // (see the reveal logic in `update`) before it's shown — the window
        // then appears already at the right size instead of opening at the
        // default and visibly resizing.
        .with_visible(false);
    // Intentionally do NOT restore fullscreen on launch — the app always opens
    // windowed; fullscreen is only ever entered when the user asks (F11).
    let opts = eframe::NativeOptions {
        viewport,
        ..Default::default()
    };
    eframe::run_native(
        "iris-gui",
        opts,
        Box::new(|cc| {
            cc.egui_ctx.set_zoom_factor(prefs.ui_scale.clamp(UI_SCALE_MIN, UI_SCALE_MAX));
            // A newer iris-gui sends SIGTERM to reclaim its ports (see
            // single_instance), and Ctrl-C or a closed terminal sends the
            // others. Close the window as File > Quit does, so `on_exit` stops
            // the machine and its disks are flushed, instead of dying at once.
            // The close skips the CHD fold, which can outlast the newer
            // instance's patience; the diff is folded on a later quit.
            #[cfg(any(target_os = "linux", target_os = "macos"))]
            {
                let ctx = cc.egui_ctx.clone();
                iris::workstation::on_exit_signal(move |_| {
                    CLOSE_ON_SIGNAL.store(true, std::sync::atomic::Ordering::SeqCst);
                    ctx.send_viewport_cmd(ViewportCommand::Close);
                    ctx.request_repaint();
                });
            }
            Ok(Box::new(App::new(prefs, std::sync::Arc::new(EguiWake(cc.egui_ctx.clone())))))
        }),
    )
}

/// The egui shell's wake: a repaint request, which eframe proxies into the
/// event loop from any thread.
struct EguiWake(egui::Context);

impl iris_gui_core::model::job::Notify for EguiWake {
    fn wake(&self) {
        self.0.request_repaint();
    }
}

