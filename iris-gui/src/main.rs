    /// Paint a framebuffer texture centred in the remaining space, on the
    /// device-pixel grid (see `fb_draw_rect`). Painted directly rather than via
    /// `egui::Image` + layout so nothing re-rounds the rect off the grid.
    /// Returns the click response and the exact rect drawn.
    fn paint_fb(ui: &mut egui::Ui, tex: &egui::TextureHandle, max_scale: f32) -> (egui::Response, egui::Rect) {
        let ppp = ui.ctx().pixels_per_point();
        let (rect, _) = fb_draw_rect(ui.available_rect_before_wrap(), tex.size_vec2(), ppp, max_scale);
        let response = ui.allocate_rect(rect, egui::Sense::click());
        let uv = egui::Rect::from_min_max(egui::pos2(0.0, 0.0), egui::pos2(1.0, 1.0));
        ui.painter().image(tex.id(), rect, uv, Color32::WHITE);
        (response, rect)
    }

    /// The View > VM screen scale in zoom-scaled points per emulated pixel —
    /// the most the picture is ever drawn at (see `fb_draw_size`). Same units
    /// as the window-fit target in `snap_window_to_fb`.
    fn fb_max_scale(&self, ctx: &egui::Context) -> f32 {
        self.app.prefs().vm_scale / ctx.zoom_factor().max(0.1)
    }

    /// Upload the newest frame from `sink` into `tex_slot`, allocating the
    /// texture on first use. Returns whether anything was uploaded.
    ///
    /// Takes the frame (a move, not a copy — the sink's buffers are pooled) and
    /// hands the buffer straight back afterwards, so a frame is never cloned on
    /// its way to the screen. Only the band of scanlines the renderer reports as
    /// changed is uploaded: `set_partial` becomes a `tex_sub_image_2d` of just
    /// those rows, so a settled guest screen costs nothing at all. See
    /// `framebuffer::FrameSink` for the hand-off and the damage rules.
    fn upload_fb_texture(
        ui: &egui::Ui,
        sink: &crate::framebuffer::FrameSink,
        tex_slot: &mut Option<egui::TextureHandle>,
        last_seq: &mut u64,
        tex_id: &str,
        max_scale: f32,
    ) -> bool {
        let seq = sink.seq();
        if seq == 0 || seq == *last_seq { return false; }
        // The frame is ours now; recycle the buffer whatever happens below so
        // the renderer's pool does not starve.
        let Some(frame) = sink.take() else { return false };
        if frame.width == 0 || frame.height == 0 { sink.recycle(frame); return false; }

        let want_nearest = match tex_slot.as_ref().map(|t| t.size_vec2()) {
            Some(px) => fb_draw_size(ui.available_size(), px, ui.ctx().pixels_per_point(), max_scale).1,
            None => true,
        };
        let opts = if want_nearest {
            egui::TextureOptions::NEAREST
        } else {
            egui::TextureOptions::LINEAR
        };

        // A band that stops short of the bottom of the picture is a patch into
        // the texture we already have; a band covering every row is a whole
        // frame and goes through `set`, which also handles a resolution change.
        let partial = frame.dirty_h > 0
            && (frame.dirty_h as usize) < frame.height
            && tex_slot.is_some();
        if partial {
            let y = frame.dirty_y as usize;
            let h = frame.dirty_h as usize;
            let w = frame.width;
            let start = y * w * 4;
            let end = (y + h) * w * 4;
            if end <= frame.rgba.len() {
                let img = egui::ColorImage::from_rgba_unmultiplied([w, h], &frame.rgba[start..end]);
                if let Some(tex) = tex_slot {
                    tex.set_partial([0, y], img, opts);
                    *last_seq = frame.seq;
                    sink.recycle(frame);
                    return true;
                }
            }
        }
        let img = egui::ColorImage::from_rgba_unmultiplied(
            [frame.width, frame.height],
            &frame.rgba,
        );
        match tex_slot {
            Some(t) => t.set(img, opts),
            None => *tex_slot = Some(ui.ctx().load_texture(tex_id, img, opts)),
        }
        *last_seq = frame.seq;
        sink.recycle(frame);
        true
    }

    fn framebuffer_panel_single(&mut self, ui: &mut egui::Ui) {
        // Lock-free check first: only take a frame (and re-upload the texture)
        // when REX3 has actually produced one. Touching the sink on every 60 fps
        // repaint regardless was ~300 MB/s of pointless copying and needless lock
        // contention with the REX3 refresh thread; now the renderer also wakes us
        // when a frame lands, so an unchanging screen costs nothing at all.
        let seq = self.app.session().handle().frame_sink.seq();
        if seq == 0 {
            ui.centered_and_justified(|ui| {
                ui.label(RichText::new(t!("fb-waiting"))
                    .color(Color32::LIGHT_GRAY));
            });
            return;
        }

        let avail = ui.available_size();
        let max_scale = self.fb_max_scale(ui.ctx());

        // Pick the texture filter from the *device-pixel* scale at which the
        // framebuffer will actually be drawn. At an integer scale (native 1×,
        // 2×, 3×, …) NEAREST keeps every emulated pixel crisp and square. At a
        // fractional scale — which is what most users hit once they set a
        // non-100% UI scale or resize the window freely — NEAREST has to double
        // some source pixels and not others, so e.g. the strokes of a "T" come
        // out uneven; LINEAR (bilinear) spreads the error and looks right. We
        // need the native size to compute this, so on the very first frame
        // (no texture yet) we default to NEAREST and correct on the next frame.
        // A fit just above an integer is drawn *at* that integer (see
        // `fb_draw_size`) — never NEAREST at a size a hair off it, which is
        // what used to drop a few rows near 1×.
        let zoom = ui.ctx().zoom_factor();
        let want_nearest = match self.fb_tex.as_ref().map(|t| t.size_vec2()) {
            Some(px) => fb_draw_size(avail, px, ui.ctx().pixels_per_point(), max_scale).1,
            None => true,
        };

        // Re-upload when the filter choice flips even if no new frame arrived
        // (a window resize can change the device-pixel scale without the guest
        // drawing anything), and when a new frame is waiting. The upload moves
        // the frame off the sink and recycles its buffer, so nothing is cloned
        // and only the damaged rows reach the GPU.
        if want_nearest != self.fb_nearest || (seq != 0 && seq != self.last_fb_seq) {
            let uploaded = Self::upload_fb_texture(
                ui,
                &self.app.session().handle().frame_sink,
                &mut self.fb_tex,
                &mut self.last_fb_seq,
                "rex3_fb",
                max_scale,
            );
            // Only claim the new filter once the texture actually carries it.
            if uploaded {
                self.fb_nearest = want_nearest;
                self.fb_took_frame = true;
            }
        }

        // Consume the snap request before the immutable borrow of self.fb_tex.
        let do_snap = std::mem::take(&mut self.pending_fb_snap);

        let mut fb_clicked = false;
        let mut new_fb_scale = 0.0;
        if let Some(tex) = &self.fb_tex {
            let tex_size = tex.size_vec2();
            // First frame after Start (or after a VM/UI scale change): size the
            // window so the picture lands at the requested VM scale.
            if do_snap && !Self::snap_window_to_fb(ui.ctx(), tex_size, avail, self.app.prefs().vm_scale) {
                self.pending_fb_snap = true;
            }
            // Draw at the chosen VM scale, centred; shrink to fit (aspect-
            // preserved) only when the window is too small for it. The snap
            // above sizes the window to the scale, so the steady-state draw is
            // stable: no per-frame resize, no jitter.
            let (response, fb_rect) = Self::paint_fb(ui, tex, max_scale);
            // Reported VM scale: device pixels per emulated pixel relative to
            // native backing (1.0 = native). The rect is in zoom-scaled points,
            // so multiply by zoom to recover the zoom-independent figure.
            if tex_size.y >= 1.0 {
                new_fb_scale = fb_rect.height() * zoom / tex_size.y;
            }
            let captured = self.app.display().captured();
            {
                // Take keyboard focus so that egui delivers Key events
                // to us instead of routing them to other widgets when
                // the user clicks into the FB.
                if response.clicked() { response.request_focus(); fb_clicked = true; }
                // While captured, keep focus pinned to the framebuffer and claim
                // the focus-navigation keys. By default egui's focus engine
                // treats Tab / arrow keys / Esc as widget navigation: it moves
                // focus off the framebuffer (and the widget it lands on can then
                // swallow later keystrokes), so those keys never reach the guest.
                // Locking the filter tells egui they belong to us — they stay in
                // the event stream and pump() forwards them. Plain Esc still
                // reaches the guest; the Ctrl+Alt+Esc release chord is detected
                // globally in pump(), before any key is forwarded.
                if captured {
                    if !response.has_focus() { response.request_focus(); }
                    ui.memory_mut(|m| m.set_focus_lock_filter(
                        response.id,
                        egui::EventFilter {
                            tab: true,
                            horizontal_arrows: true,
                            vertical_arrows: true,
                            escape: true,
                        },
                    ));
                }
            }

            // After a soft power-off the core stops the CPU but keeps the window
            // running, so the last frame stays frozen on screen. Dim it with a
            // translucent grey scrim + label so it reads as inactive, not live.
            // Keyed on `cpu_stopped` (a real CPU stop), NOT `cpu_halted` — the
            // latter also trips on 0-MIPS idle at the PROM, which would wrongly
            // dim a machine that's only paused. The frame underneath stays visible.
            if self.app.session().handle().status.cpu_stopped {
                let p = ui.painter_at(fb_rect);
                p.rect_filled(fb_rect, 0.0, Color32::from_rgba_unmultiplied(40, 42, 48, 130));
                p.text(
                    fb_rect.center(),
                    egui::Align2::CENTER_CENTER,
                    t!("fb-powered-off"),
                    egui::FontId::proportional(26.0),
                    Color32::from_rgba_unmultiplied(235, 235, 235, 235),
                );
            }
        }
        self.fb_scale = new_fb_scale;

        // When the guest becomes "safe to stop" (CPU halted — a clean IRIX
        // shutdown / `halt`), auto-release the captured mouse & keyboard so the
        // user gets their cursor back without pressing Ctrl+Alt+Esc. Edge-
        // triggered on the running→halted transition (prev is reset to true at
        // Start, so idling at the PROM during boot doesn't count), and they can
        // still click the display to re-capture.

        // A guest power-off folds pending CHD diffs at once (SessionController::drain).

        // Pump egui input → PS/2 controller. Mouse/keyboard only reach the
        // guest while captured (click the framebuffer to capture, Ctrl+Alt+Esc
        // to release), so menu clicks and config typing don't leak in.
        for action in input::pump(ui.ctx(), fb_clicked, self.app.display().captured()) {
            self.run_app(AppAction::Display(action));
        }
        input::sync_cursor(ui.ctx(), &mut self.input_state, self.app.display().captured());

    }


